_ZH2KEY = {zh: k for k, (zh, en) in CATALOG.items()}


def get_lang():
    return _LANG


def set_lang(lang):
    global _LANG
    _LANG = "en" if lang == "en" else "zh"


def tr(key, **kwargs):
    ent = CATALOG.get(key)
    if ent is None:
        k = _ZH2KEY.get(key)
        ent = CATALOG.get(k) if k else None
    text = key if ent is None else (ent[1] if _LANG == "en" else ent[0])
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


_registry = {}


def register(widget, key):
    if widget is not None:
        _registry[id(widget)] = (widget, key)


def retranslate_all():
    for w, key in list(_registry.values()):
        try:
            if hasattr(w, "setText"):
                w.setText(tr(key))
        except Exception:
            pass


def missing_en():
    return [k for k, (zh, en) in CATALOG.items() if zh == en]
